// Levels are ASCII maps, one string per row, one character per 32px tile:
//   # ground   B brick   ? coin block   C coin   E stompable walking enemy
//   S spider anchor (hangs below on a thread)   V bat (flies around this spot)
//   G giant fly (buzzes around this spot)
//   Y Fliegi (flies a sine wave around this spot)
//   K Sparky (walking spiky head, cannot be stomped)
//   W water (deadly pool)   X leaping fish (jumps out of the water below)
//   L floating log (drifts over the water and carries the player)
//   P player start   F goal (a flag, or a signpost in the woods)
// Edit freely — each column is one tile, so keep rows aligned.

export type LevelTheme = 'cave' | 'meadow' | 'forest' | 'woods';

export interface LevelDef {
  map: string[];
  theme: LevelTheme;
}

