//   # ground   B brick   ? coin block   C coin   E stompable walking enemy
//   S spider anchor (hangs below on a thread)   V bat (flies around this spot)
//   G giant fly (buzzes around this spot)
//   Y Fliegi (flies a sine wave around this spot)
//   K Sparky (walking spiky head, cannot be stomped)
//   W water (deadly pool)   X leaping fish (jumps out of the water below)
